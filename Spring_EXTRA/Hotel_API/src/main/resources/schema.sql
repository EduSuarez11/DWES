DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS roles CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;
DROP TABLE IF EXISTS hotel CASCADE;
DROP TABLE IF EXISTS habitacion CASCADE;

-- ---------- ROLES ----------
CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(40) NOT NULL UNIQUE,
                       description VARCHAR(100)
);

-- ---------- USERS ----------
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(40) NOT NULL UNIQUE,
                       password VARCHAR(255) NOT NULL,
                       full_name VARCHAR(100),
                       email VARCHAR(50) NOT NULL UNIQUE,
                       enabled BOOLEAN NOT NULL DEFAULT TRUE,

                       role_id BIGINT NOT NULL,

                       CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- Índice opcional (útil si filtras / buscas por role)
CREATE INDEX idx_users_role_id ON users(role_id);


-- =====================================================
-- TABLA: CATEGORIA
-- =====================================================

CREATE TABLE categoria (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        codigo VARCHAR(255) NOT NULL,
                        nombre VARCHAR(255) NOT NULL,
                        descripcion VARCHAR(255) NOT NULL
);

-- =====================================================
-- TABLA: HOTEL
-- =====================================================
CREATE TABLE hotel (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       codigo VARCHAR(255) NOT NULL,
                       nombre VARCHAR(255) NOT NULL,
                       descripcion VARCHAR(255) NOT NULL,
                       piscina BOOLEAN NOT NULL,
                       localidad VARCHAR(255) NOT NULL,
                       categoria_id BIGINT NOT NULL,

                       CONSTRAINT fk_hotel_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id)
);
CREATE INDEX idx_hotel_categoria_id ON hotel(categoria_id);

-- =====================================================
-- TABLA: HABITACION
-- =====================================================
CREATE TABLE habitacion (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            codigo VARCHAR(255) NOT NULL,
                            tamano INT NOT NULL,
                            doble BOOLEAN NOT NULL,
                            precio_noche DECIMAL(10,2) NOT NULL,
                            incluye_desayuno BOOLEAN NOT NULL,
                            ocupada BOOLEAN NOT NULL DEFAULT FALSE,
                            hotel_id BIGINT NOT NULL,

                            CONSTRAINT fk_habitacion_hotel FOREIGN KEY (hotel_id) REFERENCES hotel(id)
);
CREATE INDEX idx_habitacion_hotel_id ON habitacion(hotel_id);